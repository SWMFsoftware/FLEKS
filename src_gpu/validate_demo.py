#!/usr/bin/env python3
"""Run GPU PIC checks and compare decomposition/physics diagnostics.

This script uses only the Python standard library. It can also extract the
current production FLEKS field operators for the separate CPU-reference tool.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OPERATORS = (
    "grad_node_to_center", "grad_center_to_node", "div_node_to_center",
    "div_center_to_node", "curl_node_to_center", "curl_center_to_node",
    "average_node_to_center", "div_center_to_center",
)
DIAGNOSTIC = re.compile(r"(?:^|\s)DIAG\s+(.+)", re.MULTILINE)
PAIR = re.compile(r"([A-Za-z_][A-Za-z_0-9]*)=([^\s,]+)")


def extract_function(source, name):
    """Extract one definition without retyping any production coefficients."""
    match = re.search(r"^void\s+" + re.escape(name) + r"\s*\(", source, re.MULTILINE)
    if not match:
        raise ValueError(f"Production function {name} not found")
    opening = source.index("{", match.start())
    # Skip comments and literals while finding the closing function brace.
    tokens = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{}]')
    depth = 0
    for token in tokens.finditer(source, opening):
        value = token.group()
        if value == "{":
            depth += 1
        elif value == "}":
            depth -= 1
            if depth == 0:
                return source[match.start():token.end()]
    raise ValueError(f"Unclosed production function {name}")


def emit_reference(destination):
    path = ROOT / "src/GridUtility.cpp"
    raw = path.read_bytes()
    source = raw.decode()
    functions = []
    for name in OPERATORS:
        body = extract_function(source, name)
        # Only dispatch changes: execute the exact numerical expressions on
        # CPU-accessible pinned memory, independently of the demo GPU kernels.
        body = re.sub(r"\bParallelFor\b", "LoopOnCpu", body)
        body = re.sub(r"\bAMREX_GPU_DEVICE\b", "", body)
        functions.append(body)
    content = (
        "// Generated by validate_demo.py; do not edit.\n"
        f"// src/GridUtility.cpp SHA256: {hashlib.sha256(raw).hexdigest()}\n"
        "#ifndef GPU_DEMO_PRODUCTION_OPERATORS_H\n"
        "#define GPU_DEMO_PRODUCTION_OPERATORS_H\n"
        "namespace production_reference {\n"
        "using namespace amrex;\n"
        "constexpr int nDim = 3, ix_ = 0, iy_ = 1, iz_ = 2;\n"
        "constexpr bool doTiling = false;\n"
        "#define timing_func(...) ((void)0)\n"
        + "\n\n".join(functions)
        + "\n#undef timing_func\n}\n#endif\n"
    )
    destination = Path(destination)
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)
    print(f"Extracted {len(functions)} production operators to {destination}")


def parse_diagnostics(output):
    records = []
    for match in DIAGNOSTIC.finditer(output):
        record = {}
        for key, value in PAIR.findall(match.group(1)):
            try:
                record[key] = float(value)
            except ValueError:
                record[key] = value
        records.append(record)
    return records


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def validate_diagnostics(records, steps):
    require(len(records) >= 2, "Expected initial and final DIAG records")
    required = ("step", "time", "kinetic", "field", "charge", "gauss", "div_b", "residual", "particles")
    count = records[0].get("particles")
    require(count is not None and count > 0, "Initial particle count must be positive")
    for record in records:
        for key in required:
            require(key in record, f"Missing DIAG value {key}")
            require(isinstance(record[key], (int, float)) and math.isfinite(record[key]),
                    f"Nonfinite DIAG value {key}: {record.get(key)}")
        require(record["particles"] == count, "Particle count changed during periodic run")
        require(record["kinetic"] >= 0 and record["field"] >= 0, "Negative energy")
        require(abs(record["charge"]) <= 1e-9, f"Neutral plasma charge drift: {record['charge']}")
        require(record["residual"] <= 1e-7, f"True field-solver residual too large: {record['residual']}")
    require(records[-1]["step"] == steps, "Last diagnostic is not the requested final step")
    for left, right in zip(records, records[1:]):
        require(right["step"] > left["step"] and right["time"] > left["time"],
                "Diagnostic steps/times must increase")


def compare_records(left, right, label, relative=2e-7, absolute=2e-10):
    require(len(left) == len(right), f"{label}: diagnostic record counts differ")
    # Gauss maxima and Krylov residuals can be dominated by reduction-order
    # noise near zero. Compare physical global quantities, not solver work.
    for a, b in zip(left, right):
        for key in ("step", "time", "particles", "kinetic", "field", "charge"):
            require(math.isclose(a[key], b[key], rel_tol=relative, abs_tol=absolute),
                    f"{label}: {key} differs at step {a['step']}: {a[key]} vs {b[key]}")


def oscillation_frequency(records):
    """Infer plasma frequency from successive E-energy maxima (energy ~ E^2)."""
    times = [r["time"] for r in records]
    values = [r["field"] for r in records]
    peaks = []
    for i in range(1, len(values) - 1):
        if values[i] > values[i - 1] and values[i] >= values[i + 1]:
            curvature = values[i - 1] - 2 * values[i] + values[i + 1]
            offset = 0.5 * (values[i - 1] - values[i + 1]) / curvature if curvature else 0
            peaks.append(times[i] + offset * (times[i + 1] - times[i]))
    require(len(peaks) >= 3, "Need at least three E-energy maxima for a frequency check")
    periods = [b - a for a, b in zip(peaks, peaks[1:])]
    return math.pi / (sum(periods) / len(periods))


class Suite:
    def __init__(self, args, directory):
        self.args = args
        self.directory = Path(directory)
        self.results = []

    def run(self, label, parameters, ranks=1, executable=None, diagnostics=False):
        executable = str(Path(executable or self.args.executable).resolve())
        command = [executable] + [f"{key}={value}" for key, value in parameters.items()]
        if ranks > 1 or not self.args.direct:
            command = shlex.split(self.args.mpiexec) + ["-np", str(ranks)] + command
        try:
            result = subprocess.run(command, cwd=self.directory, text=True,
                                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                    timeout=self.args.timeout)
        except subprocess.TimeoutExpired as error:
            output = error.stdout or ""
            if isinstance(output, bytes):
                output = output.decode(errors="replace")
            (self.directory / f"{label}.log").write_text(output)
            raise AssertionError(f"{label}: exceeded {self.args.timeout} seconds") from error
        (self.directory / f"{label}.log").write_text(result.stdout)
        require(result.returncode == 0,
                f"{label}: exited {result.returncode}; see {self.directory / (label + '.log')}")
        require(not re.search(r"\bFAIL(?:ED)?\b", result.stdout), f"{label}: reported a failed check")
        require("PASS" in result.stdout or "DIAG" in result.stdout,
                f"{label}: no correctness result or diagnostics found")
        records = parse_diagnostics(result.stdout)
        if diagnostics:
            validate_diagnostics(records, parameters["n_step"])
        self.results.append({"case": label, "command": command, "passed": True,
                             "diagnostics": records})
        print(f"PASS {label}", flush=True)
        return records

    def execute(self):
        base = dict(n_cell=8, max_grid_size=4, particles_per_cell=8,
                    n_iter=2, n_step=8, dt=0.01, diagnostic_interval=1)
        for mode in ("fields", "particles", "deposit"):
            self.run(mode, {**base, "mode": mode})
            if self.args.mpi:
                self.run(f"{mode}-mpi2", {**base, "mode": mode}, ranks=2)
        for ppc in (1, 27):
            for mode in ("particles", "deposit"):
                self.run(f"{mode}-ppc{ppc}", {**base, "mode": mode,
                         "n_cell": 4, "particles_per_cell": ppc})
        reference = json.loads((ROOT / "src_gpu/production_one_step.json").read_text())
        one_step = self.run("production-one-step", {"mode": "implicit", **reference["parameters"],
                            "diagnostic_interval": 1}, diagnostics=True)
        for key, expected in reference["final"].items():
            actual = one_step[-1].get(key)
            require(actual is not None and math.isclose(actual, expected,
                    rel_tol=reference["relative_tolerance"], abs_tol=reference["absolute_tolerance"]),
                    f"Production CPU one-step {key}: demo {actual} vs production {expected}")
        print("PASS production-CPU-one-step", flush=True)
        coupled = {**base, "mode": "implicit", "correct_div_e": 0}
        baseline = self.run("implicit-box4", coupled, diagnostics=True)
        other = self.run("implicit-box8", {**coupled, "max_grid_size": 8}, diagnostics=True)
        compare_records(baseline, other, "box decomposition")
        print("PASS box-decomposition-invariance", flush=True)
        if self.args.mpi:
            distributed = self.run("implicit-mpi2", coupled, ranks=2, diagnostics=True)
            compare_records(baseline, distributed, "MPI decomposition")
            print("PASS mpi-decomposition-invariance", flush=True)
        self.run("implicit-divE", {**coupled, "correct_div_e": 1}, diagnostics=True)
        nonuniform = {**coupled, "initial_condition": "langmuir", "n_step": 4}
        uncorrected = self.run("langmuir-divE-off", nonuniform, diagnostics=True)
        corrected = self.run("langmuir-divE-on", {**nonuniform, "correct_div_e": 1}, diagnostics=True)
        require(corrected[-1]["gauss"] <= 0.95 * uncorrected[-1]["gauss"] + 1e-10,
                "Position correction did not reduce the nonuniform Gauss residual by5%")
        print("PASS nonuniform-divE-reduction", flush=True)
        if self.args.reference:
            self.run("production-operators", dict(n_cell=8, max_grid_size=4,
                     reference_prefix=str(self.directory / "operators")),
                     executable=self.args.reference)
        if self.args.physics:
            physics = dict(mode="implicit", n_cell=4, max_grid_size=4,
                           particles_per_cell=8, n_step=600, dt=0.01,
                           diagnostic_interval=1, theta=0.5, correct_div_e=0,
                           mass_ratio=25, perturbation=0.001)
            records = self.run("plasma-theta05", physics, diagnostics=True)
            expected = math.sqrt(4 * math.pi * (1 + 1 / physics["mass_ratio"]))
            measured = oscillation_frequency(records)
            require(abs(measured / expected - 1) < 0.06,
                    f"Plasma frequency {measured} differs from {expected} by >6%")
            energies = [r["kinetic"] + r["field"] for r in records]
            drift = max(abs(value / energies[0] - 1) for value in energies)
            require(drift < 0.02, f"theta=0.5 energy drift {drift} exceeds 2%")
            self.results.append({"case": "plasma-frequency-energy", "passed": True,
                                 "omega_expected": expected, "omega_measured": measured,
                                 "relative_energy_drift": drift})
            print(f"PASS plasma-frequency-energy omega={measured:.8g}, drift={drift:.3g}")
            half = self.run("plasma-half-dt", {**physics, "n_step": 1200, "dt": 0.005},
                            diagnostics=True)
            fine_frequency = oscillation_frequency(half)
            require(abs(fine_frequency / expected - 1) <= abs(measured / expected - 1) + 0.002,
                    "Timestep refinement increased plasma-frequency error")
            print(f"PASS timestep-refinement omega={fine_frequency:.8g}")
        (self.directory / "results.json").write_text(json.dumps(self.results, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--executable", default=str(ROOT / "bin/main_gpu.exe"))
    parser.add_argument("--mpi", action="store_true", help="also test two MPI ranks")
    parser.add_argument("--direct", action="store_true", help="launch one-rank runs directly instead of through MPI")
    parser.add_argument("--mpiexec", default="mpirun", help="MPI launcher and optional flags")
    parser.add_argument("--reference", help="path to bin/gpu_reference.exe for exact production operator checks")
    parser.add_argument("--physics", action="store_true", help="also run plasma-period, energy, and dt-refinement checks")
    parser.add_argument("--timeout", type=float, default=180)
    parser.add_argument("--output-dir", type=Path, help="retain individual logs, reference arrays, and results.json")
    parser.add_argument("--emit-production-reference", type=Path, metavar="HEADER",
                        help="extract current production operators and exit")
    args = parser.parse_args()
    if args.emit_production_reference:
        emit_reference(args.emit_production_reference)
        return 0
    require(Path(args.executable).is_file(), f"Executable not found: {args.executable}")
    if args.output_dir:
        directory = args.output_dir.resolve()
        directory.mkdir(parents=True, exist_ok=True)
        Suite(args, directory).execute()
        print(f"Logs and results: {directory}")
    else:
        with tempfile.TemporaryDirectory(prefix="fleks-gpu-checks-") as directory:
            Suite(args, directory).execute()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (AssertionError, OSError, ValueError) as error:
        print(f"FAIL {error}", file=sys.stderr)
        sys.exit(1)
