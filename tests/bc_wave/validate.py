#!/usr/bin/env python3
"""Validator for the grouped wave-injection tests (tests/bc_wave/).

Two variants are discovered from this directory:
  - PARAM.in.mono  -> base_name "bc_inject_mono"   (Bz wave, pure-EM domain)
  - PARAM.in.alfven-> base_name "bc_inject_alfven" (shear Alfven wave, hybrid)
  - PARAM.in.window-> base_name "bc_inject_window" (out-of-plane Alfven wave
                      into a flowing plasma, full PIC, 2D; source limited to
                      0 < y < 10 d_i by #WAVEBCWINDOW)

The single validate_log/validate_plot here branch on the variant's base_name
and apply variant-appropriate checks.
"""
import logging
import math
import os

from tests._shared import run_dir as _run_dir

logger = logging.getLogger(__name__)

set_run_dir = _run_dir.set_run_dir


DB_OVER_B_MAX = 0.10   # linear shear-Alfven: dB/B must stay small


# ---------------------------------------------------------------------------
# Energy-log check (shared by both variants)
# ---------------------------------------------------------------------------
def validate_log(pic_diags=None, test_name=None):
    logger.debug("Validating %s (log)...", test_name)

    if not pic_diags or len(pic_diags) < 2:
        logger.debug("  No PIC energy log found; skipping.")
        return True, "Passed (no pic log)"

    e0 = pic_diags[0].get("Etot", 0.0)
    e1 = pic_diags[-1].get("Etot", 0.0)
    logger.debug("    Etot: %.4e -> %.4e", e0, e1)

    if not (math.isfinite(e0) and math.isfinite(e1)):
        return False, "Non-finite total energy"
    if e1 <= 0:
        return False, "Final Etot is zero (wave did not inject energy)"

    if test_name and ("mono" in test_name or "explicit" in test_name):
        # Pure-EM domain begins in vacuum (e0 = 0); boundary wave injects positive energy.
        return True, "Passed (wave injected positive finite energy)"

    if e0 <= 0:
        return False, "Initial Etot is zero"

    ratio = e1 / e0
    logger.debug("    Etot_final/Etot_initial = %.4f", ratio)
    if ratio < 0.3 or ratio > 3.0:
        return False, f"Etot ratio {ratio:.3f} outside [0.3, 3.0]"

    return True, "Passed (energy finite and conserved)"


# ---------------------------------------------------------------------------
# Plot checks
# ---------------------------------------------------------------------------
def _read_plot():
    return _run_dir.load_last_out()


def _interior_max(vidx, rows, name, x_name="X"):
    xi = vidx.get(x_name)
    vi = vidx.get(name)
    if xi is None or vi is None or not rows:
        return None, None, None
    xmin = min(r[xi] for r in rows)
    xmax = max(r[xi] for r in rows)
    lo = xmin + 0.33 * (xmax - xmin)
    hi = xmin + 0.67 * (xmax - xmin)
    v_int = 0.0
    v_all = 0.0
    for r in rows:
        v_all = max(v_all, abs(r[vi]))
        if lo <= r[xi] <= hi:
            v_int = max(v_int, abs(r[vi]))
    return v_int, v_all, (xmin, xmax)


def _check_wave_in_interior(vidx, rows, field, interior_thresh=0.1):
    """The injected field must be non-zero in the interior (away from faces)."""
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    v_int, v_all, _ = _interior_max(vidx, rows, field)
    if v_int is None:
        return False, f"{field}/X not in .out"
    logger.debug("    max |%s| interior = %.4e, overall = %.4e",
                 field, v_int, v_all)
    if v_int <= 0.0:
        return False, f"{field} zero in interior (wave did not propagate)"
    if v_all > 0.0 and v_int < interior_thresh * v_all:
        return False, f"{field} barely penetrates the interior"
    return True, f"Passed ({field} present in interior)"


def validate_plot(test_name):
    logger.debug("Validating %s (plot)...", test_name)
    vidx, rows = _read_plot()
    if test_name and ("alfven" in test_name):
        return _check_alfven(vidx, rows)
    if test_name and ("window" in test_name):
        return _check_window(vidx, rows)
    if test_name and ("multiface" in test_name):
        return _check_multiface(vidx, rows)
    if test_name and ("explicit" in test_name):
        ok, msg = _check_wave_in_interior(vidx, rows, "BZ")
        if not ok:
            return False, msg
        ok, msg = _check_wave_in_interior(vidx, rows, "EY")
        if not ok:
            return False, msg
        return True, "Passed (explicit subcycled wave injected Bz and Ey into interior)"
    # default: mono wave
    return _check_wave_in_interior(vidx, rows, "BZ")


def _check_window(vidx, rows, leak_max=0.2):
    """Bz must be present inside the window (0 < y < 10) and absent outside.

    Outside the window only particle noise remains (~0.06 nT at 25 particles
    per cell, about 0.14 of the in-band rms), so leak_max sits above it.
    """
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi, bi = vidx.get("X"), vidx.get("Y"), vidx.get("BZ")
    if None in (xi, yi, bi):
        return False, "X/Y/BZ not in .out"

    def rms(ylo, yhi):
        vals = [r[bi] ** 2 for r in rows
                if 4.0 <= r[xi] <= 24.0 and ylo <= r[yi] <= yhi]
        return math.sqrt(sum(vals) / len(vals)) if vals else 0.0

    inside, outside = rms(3.5, 6.5), rms(-10.0, -2.0)
    logger.debug("    rms Bz inside window = %.4e, outside = %.4e",
                 inside, outside)
    if not (math.isfinite(inside) and math.isfinite(outside)):
        return False, "Non-finite Bz RMS inside or outside the window"
    if inside <= 0.0:
        return False, "Bz zero inside the window (wave did not propagate)"
    if outside > leak_max * inside:
        return False, (f"Bz outside the window is {outside / inside:.3f} of "
                       f"inside (> {leak_max})")
    return True, (f"Passed (Bz outside/inside window = "
                  f"{outside / inside:.3f})")


def _check_multiface(vidx, rows):
    """Verify multi-block domain bounds, per-face kicks, and corner precedence.

    PARAM.in.multiface defines a 2x2-block (16x16 cell, maxBlockSize=8) grid
    on [0, 16]^2 with outflow on (x:lo, y:lo) and wave on (x:hi, y:hi).
    In #WAVEBC, y:hi is listed FIRST (+1 nT Bz, +20 km/s uz) and x:hi SECOND
    (-1 nT Bz, -20 km/s uz). At the top-right corner node (16, 16), the x:hi
    and y:hi edge ghosts cancel in the 4-cell average, so the sign of Bz and
    uzS0 at (16, 16) is determined solely by the (x:hi, y:hi) corner ghost
    cell, which must select y:hi (+Bz, +uzS0) in #WAVEBC input order.
    """
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi = vidx.get("X"), vidx.get("Y")
    bi, uzi = vidx.get("BZ"), vidx.get("UZS0")
    if None in (xi, yi, bi, uzi):
        return False, "X/Y/BZ/UZS0 not in .out"

    xmax = max(r[xi] for r in rows)
    ymax = max(r[yi] for r in rows)

    # 1. Lower-left block and inter-block seam (x <= 8, y <= 8): must stay
    #    unperturbed (no spurious block-bound wave injection on non-wave faces).
    ll_bz = max((abs(r[bi]) for r in rows if r[xi] <= 8.5 and r[yi] <= 8.5),
                default=0.0)
    ll_uz = max((abs(r[uzi]) for r in rows if r[xi] <= 8.5 and r[yi] <= 8.5),
                default=0.0)
    if ll_bz > 1.0e-3 or ll_uz > 0.5:
        return False, (f"Spurious wave on non-wave block bounds: "
                       f"max |Bz|={ll_bz:.3e}, max |uzS0|={ll_uz:.3e}")

    # 2. y:hi edge away from corners: must have positive Bz and uzS0 (+10 km/s
    #    at wall node), proving x:hi's -20 km/s kick is not summed onto y:hi.
    yhi_rows = [r for r in rows
                if abs(r[yi] - ymax) < 1e-4 and 2.0 <= r[xi] <= 12.0]
    xhi_rows = [r for r in rows
                if abs(r[xi] - xmax) < 1e-4 and 2.0 <= r[yi] <= 12.0]
    if not yhi_rows or not xhi_rows:
        return False, "Missing y:hi or x:hi boundary nodes in .out"

    yhi_bz = sum(r[bi] for r in yhi_rows) / len(yhi_rows)
    yhi_uz = sum(r[uzi] for r in yhi_rows) / len(yhi_rows)
    xhi_bz = sum(r[bi] for r in xhi_rows) / len(xhi_rows)
    xhi_uz = sum(r[uzi] for r in xhi_rows) / len(xhi_rows)
    if not (yhi_bz > 0.2 and yhi_uz > 5.0):
        return False, (f"y:hi face expected Bz > 0.2 nT, uzS0 > 5 km/s; "
                       f"got Bz={yhi_bz:.3f}, uzS0={yhi_uz:.3f}")
    if not (xhi_bz < -0.2 and xhi_uz < -5.0):
        return False, (f"x:hi face expected Bz < -0.2 nT, uzS0 < -5 km/s; "
                       f"got Bz={xhi_bz:.3f}, uzS0={xhi_uz:.3f}")

    # 3. Top-right corner node (xmax, ymax): y:hi precedes x:hi in #WAVEBC, so
    #    both apply_wave_field and wave_velocity_kick must select y:hi at the
    #    corner ghost cell, yielding Bz > 0 and uzS0 > 0 (~ +5 km/s).
    corner = [r for r in rows
              if abs(r[xi] - xmax) < 1e-4 and abs(r[yi] - ymax) < 1e-4]
    if not corner:
        return False, "Corner node (xmax, ymax) not found in .out"
    c_bz, c_uz = corner[0][bi], corner[0][uzi]
    if not (c_bz > 0.1 and c_uz > 2.5):
        return False, (f"Corner (xmax, ymax) expected y:hi precedence "
                       f"(Bz > 0.1 nT, uzS0 > 2.5 km/s); got "
                       f"Bz={c_bz:.3f}, uzS0={c_uz:.3f}")

    return True, (f"Passed (y:hi uz={yhi_uz:.2f}, x:hi uz={xhi_uz:.2f}, "
                  f"corner Bz={c_bz:.3f}, corner uz={c_uz:.2f})")


def _check_alfven(vidx, rows):
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"

    by_int, by_all, _ = _interior_max(vidx, rows, "BY")
    bx_guide_vals = [abs(r[vidx["BX"]]) for r in rows] if "BX" in vidx else [0.0]
    bx_guide = max(bx_guide_vals)
    bx_guide_min = min(bx_guide_vals)
    logger.debug("    max |By| interior = %.4e, overall = %.4e, |Bx| = %.4e (min=%.4e)",
                 by_int, by_all, bx_guide, bx_guide_min)

    if bx_guide <= 0.0 or bx_guide_min < 0.8 * bx_guide:
        return False, f"Bx guide field corrupted (min={bx_guide_min:.4e}, max={bx_guide:.4e})"

    if by_int is None or by_int <= 0.0:
        return False, "By zero in interior (Alfven wave did not propagate)"

    if bx_guide > 0.0 and by_int > DB_OVER_B_MAX * bx_guide:
        return False, (f"By/Bx = {by_int/bx_guide:.3f} exceeds "
                       f"{DB_OVER_B_MAX*100:.0f}% -- not a linear Alfven wave")

    return True, "Passed (By wave present in interior, dB/B small, Bx guide preserved)"
