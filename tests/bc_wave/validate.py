#!/usr/bin/env python3
"""Validator for the grouped wave-injection tests (tests/bc_wave/).

Two variants are discovered from this directory:
  - PARAM.in.mono  -> base_name "bc_inject_mono"   (Bz wave, pure-EM domain)
  - PARAM.in.alfven-> base_name "bc_inject_alfven" (shear Alfven wave, hybrid)
  - PARAM.in.window-> base_name "bc_inject_window" (out-of-plane Alfven wave
                      into a flowing plasma, full PIC, 2D; source limited to
                      0 < y < 10 d_i by #WAVEBCWINDOW)

The single validate_log/validate_plot here branch on the variant's base_name
and apply variant-appropriate checks.
"""
import logging
import math
import os

from tests._shared import run_dir as _run_dir

logger = logging.getLogger(__name__)

set_run_dir = _run_dir.set_run_dir


DB_OVER_B_MAX = 0.10   # linear shear-Alfven: dB/B must stay small


# ---------------------------------------------------------------------------
# Energy-log check (shared by both variants)
# ---------------------------------------------------------------------------
def validate_log(pic_diags=None, test_name=None):
    logger.debug("Validating %s (log)...", test_name)

    if test_name and "turb_restart" in test_name:
        return _validate_turb_restart_log(pic_diags=pic_diags, test_name=test_name)

    if not pic_diags or len(pic_diags) < 2:
        logger.debug("  No PIC energy log found; skipping.")
        return True, "Passed (no pic log)"

    e0 = pic_diags[0].get("Etot", 0.0)
    e1 = pic_diags[-1].get("Etot", 0.0)
    logger.debug("    Etot: %.4e -> %.4e", e0, e1)

    if not (math.isfinite(e0) and math.isfinite(e1)):
        return False, "Non-finite total energy"
    if e1 <= 0:
        return False, "Final Etot is zero (wave did not inject energy)"

    if test_name and ("mono" in test_name or "explicit" in test_name):
        # Pure-EM domain begins in vacuum (e0 = 0); boundary wave injects positive energy.
        return True, "Passed (wave injected positive finite energy)"

    if e0 <= 0:
        return False, "Initial Etot is zero"

    ratio = e1 / e0
    logger.debug("    Etot_final/Etot_initial = %.4f", ratio)
    if ratio < 0.3 or ratio > 3.0:
        return False, f"Etot ratio {ratio:.3f} outside [0.3, 3.0]"

    return True, "Passed (energy finite and conserved)"


# ---------------------------------------------------------------------------
# Plot checks
# ---------------------------------------------------------------------------
def _read_plot():
    return _run_dir.load_last_out()


def _interior_max(vidx, rows, name, x_name="X"):
    xi = vidx.get(x_name)
    vi = vidx.get(name)
    if xi is None or vi is None or not rows:
        return None, None, None
    xmin = min(r[xi] for r in rows)
    xmax = max(r[xi] for r in rows)
    lo = xmin + 0.33 * (xmax - xmin)
    hi = xmin + 0.67 * (xmax - xmin)
    v_int = 0.0
    v_all = 0.0
    for r in rows:
        v_all = max(v_all, abs(r[vi]))
        if lo <= r[xi] <= hi:
            v_int = max(v_int, abs(r[vi]))
    return v_int, v_all, (xmin, xmax)


def _check_wave_in_interior(vidx, rows, field, interior_thresh=0.1):
    """The injected field must be non-zero in the interior (away from faces)."""
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    v_int, v_all, _ = _interior_max(vidx, rows, field)
    if v_int is None:
        return False, f"{field}/X not in .out"
    logger.debug("    max |%s| interior = %.4e, overall = %.4e",
                 field, v_int, v_all)
    if v_int <= 0.0:
        return False, f"{field} zero in interior (wave did not propagate)"
    if v_all > 0.0 and v_int < interior_thresh * v_all:
        return False, f"{field} barely penetrates the interior"
    return True, f"Passed ({field} present in interior)"


def validate_plot(test_name):
    logger.debug("Validating %s (plot)...", test_name)
    if test_name and ("turb_restart" in test_name):
        return _validate_turb_restart_plot(test_name)
    vidx, rows = _read_plot()
    if test_name and ("alfven_inflow" in test_name):
        return _check_alfven_inflow(vidx, rows)
    if test_name and ("alfven" in test_name):
        return _check_alfven(vidx, rows)
    if test_name and ("window" in test_name):
        return _check_window(vidx, rows)
    if test_name and ("turb_multiface" in test_name):
        return _check_turb_multiface(vidx, rows)
    if test_name and ("multiface" in test_name):
        return _check_multiface(vidx, rows)
    if test_name and ("turbulent" in test_name):
        return _check_turbulent(vidx, rows)
    if test_name and ("explicit" in test_name):
        ok, msg = _check_wave_in_interior(vidx, rows, "BZ")
        if not ok:
            return False, msg
        ok, msg = _check_wave_in_interior(vidx, rows, "EY")
        if not ok:
            return False, msg
        return True, "Passed (explicit subcycled wave injected Bz and Ey into interior)"
    # default: mono wave
    return _check_wave_in_interior(vidx, rows, "BZ")


def _check_window(vidx, rows, leak_max=0.2):
    """Bz must be present inside the window (0 < y < 10) and absent outside.

    Outside the window only particle noise remains (~0.06 nT at 25 particles
    per cell, about 0.14 of the in-band rms), so leak_max sits above it.
    """
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi, bi = vidx.get("X"), vidx.get("Y"), vidx.get("BZ")
    if None in (xi, yi, bi):
        return False, "X/Y/BZ not in .out"

    def rms(ylo, yhi):
        vals = [r[bi] ** 2 for r in rows
                if 4.0 <= r[xi] <= 24.0 and ylo <= r[yi] <= yhi]
        return math.sqrt(sum(vals) / len(vals)) if vals else 0.0

    inside, outside = rms(3.5, 6.5), rms(-10.0, -2.0)
    logger.debug("    rms Bz inside window = %.4e, outside = %.4e",
                 inside, outside)
    if not (math.isfinite(inside) and math.isfinite(outside)):
        return False, "Non-finite Bz RMS inside or outside the window"
    if inside <= 0.0:
        return False, "Bz zero inside the window (wave did not propagate)"
    if outside > leak_max * inside:
        return False, (f"Bz outside the window is {outside / inside:.3f} of "
                       f"inside (> {leak_max})")
    return True, (f"Passed (Bz outside/inside window = "
                  f"{outside / inside:.3f})")


def _check_multiface(vidx, rows):
    """Verify multi-block domain bounds, per-face kicks, and corner precedence.

    PARAM.in.multiface defines a 2x2-block (16x16 cell, maxBlockSize=8) grid
    on [0, 16]^2 with outflow on (x:lo, y:lo) and wave on (x:hi, y:hi).
    In #WAVEBC, y:hi is listed FIRST (+1 nT Bz, +20 km/s uz) and x:hi SECOND
    (-1 nT Bz, -20 km/s uz). At the top-right corner node (16, 16), the x:hi
    and y:hi edge ghosts cancel in the 4-cell average, so the sign of Bz and
    uzS0 at (16, 16) is determined solely by the (x:hi, y:hi) corner ghost
    cell, which must select y:hi (+Bz, +uzS0) in #WAVEBC input order.
    """
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi = vidx.get("X"), vidx.get("Y")
    bi, uzi = vidx.get("BZ"), vidx.get("UZS0")
    if None in (xi, yi, bi, uzi):
        return False, "X/Y/BZ/UZS0 not in .out"

    xmax = max(r[xi] for r in rows)
    ymax = max(r[yi] for r in rows)

    # 1. Lower-left block and inter-block seam (x <= 8, y <= 8): must stay
    #    unperturbed (no spurious block-bound wave injection on non-wave faces).
    ll_bz = max((abs(r[bi]) for r in rows if r[xi] <= 8.5 and r[yi] <= 8.5),
                default=0.0)
    ll_uz = max((abs(r[uzi]) for r in rows if r[xi] <= 8.5 and r[yi] <= 8.5),
                default=0.0)
    if ll_bz > 1.0e-3 or ll_uz > 0.5:
        return False, (f"Spurious wave on non-wave block bounds: "
                       f"max |Bz|={ll_bz:.3e}, max |uzS0|={ll_uz:.3e}")

    # 2. y:hi edge away from corners: must have positive Bz and uzS0 (+10 km/s
    #    at wall node), proving x:hi's -20 km/s kick is not summed onto y:hi.
    yhi_rows = [r for r in rows
                if abs(r[yi] - ymax) < 1e-4 and 2.0 <= r[xi] <= 12.0]
    xhi_rows = [r for r in rows
                if abs(r[xi] - xmax) < 1e-4 and 2.0 <= r[yi] <= 12.0]
    if not yhi_rows or not xhi_rows:
        return False, "Missing y:hi or x:hi boundary nodes in .out"

    yhi_bz = sum(r[bi] for r in yhi_rows) / len(yhi_rows)
    yhi_uz = sum(r[uzi] for r in yhi_rows) / len(yhi_rows)
    xhi_bz = sum(r[bi] for r in xhi_rows) / len(xhi_rows)
    xhi_uz = sum(r[uzi] for r in xhi_rows) / len(xhi_rows)
    if not (yhi_bz > 0.2 and yhi_uz > 5.0):
        return False, (f"y:hi face expected Bz > 0.2 nT, uzS0 > 5 km/s; "
                       f"got Bz={yhi_bz:.3f}, uzS0={yhi_uz:.3f}")
    if not (xhi_bz < -0.2 and xhi_uz < -5.0):
        return False, (f"x:hi face expected Bz < -0.2 nT, uzS0 < -5 km/s; "
                       f"got Bz={xhi_bz:.3f}, uzS0={xhi_uz:.3f}")

    # 3. Top-right corner node (xmax, ymax): y:hi precedes x:hi in #WAVEBC, so
    #    both apply_wave_field and wave_velocity_kick must select y:hi at the
    #    corner ghost cell, yielding Bz > 0 and uzS0 > 0 (~ +5 km/s).
    corner = [r for r in rows
              if abs(r[xi] - xmax) < 1e-4 and abs(r[yi] - ymax) < 1e-4]
    if not corner:
        return False, "Corner node (xmax, ymax) not found in .out"
    c_bz, c_uz = corner[0][bi], corner[0][uzi]
    if not (c_bz > 0.1 and c_uz > 2.5):
        return False, (f"Corner (xmax, ymax) expected y:hi precedence "
                       f"(Bz > 0.1 nT, uzS0 > 2.5 km/s); got "
                       f"Bz={c_bz:.3f}, uzS0={c_uz:.3f}")

    return True, (f"Passed (y:hi uz={yhi_uz:.2f}, x:hi uz={xhi_uz:.2f}, "
                  f"corner Bz={c_bz:.3f}, corner uz={c_uz:.2f})")


def _check_turbulent(vidx, rows):
    """Verify #TURBULENTINFLOW mode synthesis, Walen correlation, and JSON dump."""
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi = vidx.get("X"), vidx.get("Y")
    bxi, byi, bzi = vidx.get("BX"), vidx.get("BY"), vidx.get("BZ")
    uzi = vidx.get("UZS0")
    if None in (xi, yi, bxi, byi, bzi, uzi):
        return False, "X/Y/BX/BY/BZ/UZS0 not in .out"

    # 1. Verify wave_modes.json was written by Rank 0 with 8 periodic-snapped modes
    import json
    mode_path = os.path.join(_run_dir.RUN_DIR, "wave_modes.json")
    if not os.path.isfile(mode_path):
        return False, "wave_modes.json was not written by #TURBULENTINFLOW"
    with open(mode_path) as f:
        tab = json.load(f)
    modes = tab.get("modes", [])
    if len(modes) != 8:
        return False, f"Expected 8 modes in wave_modes.json, got {len(modes)}"
    ly_m = 32.0 * 1.316e5
    dky = 2.0 * math.pi / ly_m
    for m in modes:
        ky = m["k"][1]
        if abs(ky / dky - round(ky / dky)) > 1.0e-4:
            return False, f"Mode ky={ky} not snapped to 2*pi/Ly={dky}"

    # 2. Check broadband Bz injection and Walen relation in upstream-filled region
    interior = [r for r in rows if 8.0 <= r[xi] <= 28.0]
    if not interior:
        return False, "No interior points in [8, 28] d_i"

    bz_vals = [r[bzi] for r in interior]
    uz_vals = [r[uzi] for r in interior]
    bz_rms = math.sqrt(sum(b * b for b in bz_vals) / len(bz_vals))
    if not (0.5 <= bz_rms <= 2.2):
        return False, f"Turbulent Bz RMS {bz_rms:.3f} nT outside expected [0.5, 2.2] nT"

    # Walen speed conversion: vA / B0 = 1 / sqrt(mu0 * rho0) ~= 12.606 (km/s)/nT
    va_per_nt = 63.03 / 5.0
    x_walen = [b * va_per_nt for b in bz_vals]
    mx = sum(x_walen) / len(x_walen)
    my = sum(uz_vals) / len(uz_vals)
    sxx = sum((x - mx) ** 2 for x in x_walen)
    syy = sum((y - my) ** 2 for y in uz_vals)
    sxy = sum((x - mx) * (y - my) for x, y in zip(x_walen, uz_vals))
    slope = sxy / sxx if sxx > 0 else 0.0
    corr = sxy / math.sqrt(sxx * syy) if (sxx > 0 and syy > 0) else 0.0
    if corr < 0.85 or not (0.70 <= slope <= 1.30):
        return False, (f"Walen relation violated: slope={slope:.3f}, "
                       f"corr={corr:.3f} (expected slope~1, corr>=0.85)")

    return True, (f"Passed (Bz_rms={bz_rms:.2f} nT, Walen slope={slope:.2f}, "
                  f"r={corr:.3f})")


def _check_turb_multiface(vidx, rows):
    """Verify non-periodic 3-face #TURBULENTINFLOW + #PLANETRADIUS + C^2 taper."""
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"
    xi, yi = vidx.get("X"), vidx.get("Y")
    bzi, ezi, uzi = vidx.get("BZ"), vidx.get("EZ"), vidx.get("UZS0")
    if None in (xi, yi, bzi, ezi, uzi):
        return False, "X/Y/BZ/EZ/UZS0 not in .out"

    # 1. Verify wave_modes.json uses R_E -> SI conversion (lmin = 0.2*6.378e6,
    #    lmax = 0.6*6.378e6), accurate n = 3.0 /cc, and unquantized non-periodic k.
    import json
    r_planet = 6.378e6
    l_norm = 1.316e5
    mhd2no = r_planet / l_norm

    mode_path = os.path.join(_run_dir.RUN_DIR, "wave_modes.json")
    if not os.path.isfile(mode_path):
        return False, "wave_modes.json was not written by #TURBULENTINFLOW"
    with open(mode_path) as f:
        tab = json.load(f)
    info = tab.get("info", {})
    modes = tab.get("modes", [])
    if len(modes) != 8:
        return False, f"Expected 8 modes in wave_modes.json, got {len(modes)}"

    lmin_exp = 0.2 * r_planet
    lmax_exp = 0.6 * r_planet
    if abs(info.get("lmin", 0.0) - lmin_exp) > 1.0e-3 * lmin_exp:
        return False, f"Expected lmin={lmin_exp:.6e}, got {info.get('lmin')}"
    if abs(info.get("lmax", 0.0) - lmax_exp) > 1.0e-3 * lmax_exp:
        return False, f"Expected lmax={lmax_exp:.6e}, got {info.get('lmax')}"
    if abs(info.get("n", 0.0) - 3.0) > 1.0e-3:
        return False, f"Expected upstream n=3.0 /cc, got {info.get('n')}"

    ly_m = 32.0 * l_norm
    dky = 2.0 * math.pi / ly_m
    n_non_int = sum(
        1 for m in modes if abs(m["k"][1] / dky - round(m["k"][1] / dky)) > 1.0e-3
    )
    if n_non_int == 0:
        return False, "All ky values appear snapped to periodic harmonics in non-periodic box"

    # 2. Upstream interior check (coordinates in .out are in R_E via #PLANETRADIUS).
    interior = [
        r for r in rows
        if 18.0 <= r[xi] * mhd2no <= 30.0 and -12.0 <= r[yi] * mhd2no <= 12.0
    ]
    if not interior:
        return False, "No interior points in [18, 30] x [-12, 12] d_i"

    bz_vals = [r[bzi] for r in interior]
    uz_vals = [r[uzi] for r in interior]
    bz_rms = math.sqrt(sum(b * b for b in bz_vals) / len(bz_vals))
    if not (0.4 <= bz_rms <= 2.2):
        return False, f"Upstream Bz RMS {bz_rms:.3f} nT outside [0.4, 2.2] nT"

    # Total kinetic mass density with mi/me = 25 -> 1.04 * m_i: va = 61.81 km/s
    va_per_nt = (63.03 / math.sqrt(1.04)) / 5.0
    x_walen = [b * va_per_nt for b in bz_vals]
    mx = sum(x_walen) / len(x_walen)
    my = sum(uz_vals) / len(uz_vals)
    sxx = sum((x - mx) ** 2 for x in x_walen)
    syy = sum((y - my) ** 2 for y in uz_vals)
    sxy = sum((x - mx) * (y - my) for x, y in zip(x_walen, uz_vals))
    slope = sxy / sxx if sxx > 0 else 0.0
    corr = sxy / math.sqrt(sxx * syy) if (sxx > 0 and syy > 0) else 0.0
    if corr < 0.80 or not (0.65 <= slope <= 1.35):
        return False, (f"Walen relation violated: slope={slope:.3f}, "
                       f"corr={corr:.3f} (expected slope~1, corr>=0.80)")

    # 3. Verify spatial window taper along y:lo and y:hi walls:
    #    x < 8 d_i has w=0, x > 16 d_i has w=1.
    ymin = min(r[yi] for r in rows)
    ymax = max(r[yi] for r in rows)
    xmax = max(r[xi] for r in rows)
    wall_dn = [
        r for r in rows
        if (abs(r[yi] - ymin) < 1e-6 or abs(r[yi] - ymax) < 1e-6)
        and r[xi] * mhd2no < 6.0
    ]
    wall_up = [
        r for r in rows
        if (abs(r[yi] - ymin) < 1e-6 or abs(r[yi] - ymax) < 1e-6)
        and r[xi] * mhd2no > 20.0
    ]
    if not wall_dn or not wall_up:
        return False, "Missing y-wall samples for taper verification"
    rms_dn = math.sqrt(sum(r[bzi] ** 2 for r in wall_dn) / len(wall_dn))
    rms_up = math.sqrt(sum(r[bzi] ** 2 for r in wall_up) / len(wall_up))
    if rms_up <= 0.1 or rms_dn > 0.25 * rms_up:
        return False, (f"Side-wall taper failed: downstream rms={rms_dn:.3f} nT, "
                       f"upstream rms={rms_up:.3f} nT")

    # 4. Upstream corners (x:hi, y:lo) and (x:hi, y:hi) must stay finite and bounded.
    corners = [
        r for r in rows
        if abs(r[xi] - xmax) < 1e-6
        and (abs(r[yi] - ymin) < 1e-6 or abs(r[yi] - ymax) < 1e-6)
    ]
    if len(corners) < 2:
        return False, "Missing upstream corner nodes in .out"
    for r in corners:
        if not (math.isfinite(r[bzi]) and math.isfinite(r[ezi])):
            return False, "Non-finite Bz or Ez at upstream corner"
        if abs(r[bzi]) > 25.0 or abs(r[ezi]) > 50000.0:
            return False, (f"Upstream corner spike: Bz={r[bzi]:.3f} nT, "
                           f"Ez={r[ezi]:.1f} uV/m")

    return True, (f"Passed (Bz_rms={bz_rms:.2f} nT, Walen slope={slope:.2f}, "
                  f"r={corr:.3f}, wall dn/up={rms_dn/rms_up:.3f})")


def _validate_turb_restart_log(pic_diags=None, test_name=None):
    """Run checkpoint-restart comparison including wave_modes.json equality."""
    import json
    import shutil
    from tests.restart import validate as _restart_val

    _restart_val.set_run_dir(_run_dir.RUN_DIR)
    mode_path = os.path.join(_run_dir.RUN_DIR, "wave_modes.json")
    mode_backup = os.path.join(_run_dir.RUN_DIR, "wave_modes_uninterrupted.json")
    if not os.path.isfile(mode_path):
        return False, "wave_modes.json missing before restart"
    shutil.copy2(mode_path, mode_backup)

    try:
        ok, msg = _restart_val.validate_log(pic_diags=pic_diags, test_name=test_name)
        if not ok:
            return False, msg

        if not os.path.isfile(mode_path):
            return False, "wave_modes.json was not written by restarted run"
        with open(mode_backup) as f_ref, open(mode_path) as f_rst:
            ref_tab = json.load(f_ref)
            rst_tab = json.load(f_rst)
        if ref_tab != rst_tab:
            return False, "wave_modes.json differs after restart"

        return True, f"{msg}; wave_modes.json identical"
    finally:
        if os.path.exists(mode_backup):
            os.remove(mode_backup)


def _validate_turb_restart_plot(test_name=None):
    from tests.restart import validate as _restart_val
    return _restart_val.validate_plot(test_name=test_name)


def _check_alfven(vidx, rows):
    if not vidx or not rows:
        return False, "No .out data generated by PostProc"

    by_int, by_all, _ = _interior_max(vidx, rows, "BY")
    bx_guide_vals = [abs(r[vidx["BX"]]) for r in rows] if "BX" in vidx else [0.0]
    bx_guide = max(bx_guide_vals)
    bx_guide_min = min(bx_guide_vals)
    logger.debug("    max |By| interior = %.4e, overall = %.4e, |Bx| = %.4e (min=%.4e)",
                 by_int, by_all, bx_guide, bx_guide_min)

    if bx_guide <= 0.0 or bx_guide_min < 0.8 * bx_guide:
        return False, f"Bx guide field corrupted (min={bx_guide_min:.4e}, max={bx_guide:.4e})"

    if by_int is None or by_int <= 0.0:
        return False, "By zero in interior (Alfven wave did not propagate)"

    if bx_guide > 0.0 and by_int > DB_OVER_B_MAX * bx_guide:
        return False, (f"By/Bx = {by_int/bx_guide:.3f} exceeds "
                       f"{DB_OVER_B_MAX*100:.0f}% -- not a linear Alfven wave")

    return True, "Passed (By wave present in interior, dB/B small, Bx guide preserved)"


def _check_alfven_inflow(vidx, rows):
    """Verify combined wave + inflow boundary injects By AND Walen uyS0."""
    ok, msg = _check_alfven(vidx, rows)
    if not ok:
        return False, msg

    xi = vidx.get("X")
    byi = vidx.get("BY")
    uyi = vidx.get("UYS0")
    if None in (xi, byi, uyi):
        return False, "X/BY/UYS0 missing from .out"

    xmin = min(r[xi] for r in rows)
    xmax = max(r[xi] for r in rows)
    lo = xmin + 0.15 * (xmax - xmin)
    hi = xmin + 0.70 * (xmax - xmin)
    sel = [r for r in rows if lo <= r[xi] <= hi]
    if len(sel) < 4:
        return False, "Insufficient interior points for Walen correlation"

    bys = [r[byi] for r in sel]
    uys = [r[uyi] for r in sel]
    if max(abs(u) for u in uys) <= 1e-4:
        return False, "uyS0 zero in interior (waveVelocityKick missing on inflow face)"

    m_by = sum(bys) / len(bys)
    m_uy = sum(uys) / len(uys)
    sbb = sum((b - m_by) ** 2 for b in bys)
    suu = sum((u - m_uy) ** 2 for u in uys)
    sbu = sum((b - m_by) * (u - m_uy) for b, u in zip(bys, uys))
    corr = sbu / math.sqrt(sbb * suu) if (sbb > 0.0 and suu > 0.0) else 0.0
    logger.debug("    [ALFVEN_INFLOW] corr(By, uyS0) = %.4f, max|uyS0| = %.4e",
                 corr, max(abs(u) for u in uys))
    if corr > -0.80:
        return False, f"Walen anti-correlation corr(By, uyS0) = {corr:.3f} > -0.80"

    return True, f"Passed (wave+inflow By & Walen uyS0 propagated: corr={corr:.3f})"
